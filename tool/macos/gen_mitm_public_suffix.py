#!/usr/bin/env python3
"""Writes macos/Runner/MitmPublicSuffixList.swift from the public suffix list
the Core's golang.org/x/net carries, so the app's signer and the Core refuse
the same over-broad hostnames.

usage: tool/macos/gen_mitm_public_suffix.py [--check]

Reads the module from `go env GOMODCACHE` at the version core/go.mod requires.
--check exits 1 when the Swift file differs from what would be written.
"""

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / 'macos/Runner/MitmPublicSuffixList.swift'


def module_dir():
    go_mod = (ROOT / 'core/go.mod').read_text()
    version = re.search(r'^\s*golang\.org/x/net (v\S+)', go_mod, re.M).group(1)
    cache = subprocess.run(['go', 'env', 'GOMODCACHE'], cwd=ROOT / 'core', check=True,
                           capture_output=True, text=True).stdout.strip()
    return Path(cache) / f'golang.org/x/net@{version}/publicsuffix', version


def render():
    directory, module_version = module_dir()
    table = (directory / 'table_test.go').read_text()
    body = table[table.index('var rules = [...]string{'):]
    body = body[:body.index('\n}\n')]
    rules = re.findall(r'^\t"([^"]+)",$', body, re.M)
    if len(rules) < 5000 or any(not re.fullmatch(r'[!*a-z0-9.-]+', rule) for rule in rules):
        raise SystemExit('unexpected rules in ' + str(directory))
    list_version = re.search(r'const version = "([^"]+)"', (directory / 'table.go').read_text()).group(1)
    lines = [
        '// Generated by tool/macos/gen_mitm_public_suffix.py; DO NOT EDIT.',
        f'// golang.org/x/net {module_version}: {list_version}',
        '',
        '// One rule a line: a suffix, *.suffix or !exception, as the Core reads them.',
        'let mitmPublicSuffixRules = """',
        *rules,
        '"""',
        '',
    ]
    return '\n'.join(lines)


def main():
    text = render()
    if '--check' in sys.argv[1:]:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            print(f'{OUTPUT.relative_to(ROOT)} is stale; run {Path(__file__).relative_to(ROOT)}', file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
